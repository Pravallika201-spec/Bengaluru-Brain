# LOAD PRIORITY AREAS
# ============================================================

def load_priority_areas():

    print("\nLoading priority areas...")

    if not os.path.exists(INPUT_FILE):

        raise FileNotFoundError(
            "\nInput file not found:\n"
            f"{INPUT_FILE}\n"
        )

    df = pd.read_csv(
        INPUT_FILE
    )

    print(
        f"Priority areas loaded: {len(df)}"
    )

    required_columns = [

        "area_name",

        "latitude",

        "longitude",

        "predicted_waste_kg",

        "additional_event_waste_kg",

        "area_risk",

        "area_priority_score"

    ]

    missing_columns = [

        column

        for column in required_columns

        if column not in df.columns

    ]

    if missing_columns:

        raise ValueError(
            "\nMissing required columns:\n"
            f"{missing_columns}"
        )

    return df


# ============================================================
# CALCULATE ROUTING PRIORITY
# ============================================================

def calculate_routing_priority(row):

    """
    Combine risk, priority score and event waste
    into a single routing priority score.
    """

    risk_weights = {

        "CRITICAL": 1.00,

        "HIGH": 0.80,

        "MEDIUM": 0.50,

        "LOW": 0.20

    }

    risk = str(
        row["area_risk"]
    ).upper()

    risk_weight = risk_weights.get(
        risk,
        0.20
    )

    priority_score = float(
        row["area_priority_score"]
    )

    predicted_waste = float(
        row["predicted_waste_kg"]
    )

    event_waste = float(
        row["additional_event_waste_kg"]
    )

    # Event waste relative to predicted waste
    if predicted_waste > 0:

        event_factor = (
            event_waste
            /
            predicted_waste
        )

    else:

        event_factor = 0.0

    # Final routing priority
    routing_priority = (

        0.50
        *
        priority_score

        +

        0.30
        *
        risk_weight

        +

        0.20
        *
        min(
            event_factor,
            1.0
        )

    )

    return routing_priority


# ============================================================
# PREPARE ROUTING DATA
# ============================================================

def prepare_routing_data(df):

    print(
        "\nPreparing routing priorities..."
    )

    df = df.copy()

    df[
        "routing_priority"
    ] = df.apply(
        calculate_routing_priority,
        axis=1
    )

    # Highest priority first
    df = df.sort_values(
        "routing_priority",
        ascending=False
    ).reset_index(
        drop=True
    )

    return df


