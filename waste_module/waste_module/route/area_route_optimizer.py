# AREA ROUTE OPTIMIZATION
# ============================================================

def optimize_route(df):

    print(
        "\nOptimizing area route..."
    )

    if len(df) == 0:

        raise ValueError(
            "No priority areas available."
        )

    # Copy remaining locations
    remaining = df.copy()

    route = []

    # --------------------------------------------------------
    # Start with highest priority area
    # --------------------------------------------------------

    current_index = (
        remaining.index[0]
    )

    current_row = (
        remaining.loc[
            current_index
        ]
    )

    route.append(
        current_row
    )

    remaining = (
        remaining.drop(
            current_index
        )
    )

    previous_lat = float(
        current_row["latitude"]
    )

    previous_lon = float(
        current_row["longitude"]
    )

    # --------------------------------------------------------
    # Select next area
    # --------------------------------------------------------

    while len(remaining) > 0:

        best_index = None

        best_score = (
            float("-inf")
        )

        best_distance = None

        for index, candidate in (
            remaining.iterrows()
        ):

            candidate_lat = float(
                candidate["latitude"]
            )

            candidate_lon = float(
                candidate["longitude"]
            )

            # Distance from current area
            distance = haversine_distance(

                previous_lat,

                previous_lon,

                candidate_lat,

                candidate_lon

            )

            priority = float(
                candidate[
                    "routing_priority"
                ]
            )

            # Nearby areas receive a higher score
            distance_factor = (
                1.0
                /
                (
                    1.0
                    +
                    distance
                )
            )

            # Combined priority + distance
            score = (

                0.65
                *
                priority

                +

                0.35
                *
                distance_factor

            )

            if score > best_score:

                best_score = score

                best_index = index

                best_distance = distance

        # Add selected area to route
        next_row = (
            remaining.loc[
                best_index
            ]
        )

        route.append(
            next_row
        )

        # Update current position
        previous_lat = float(
            next_row["latitude"]
        )

        previous_lon = float(
            next_row["longitude"]
        )

        # Remove from remaining
        remaining = (
            remaining.drop(
                best_index
            )
        )

    # Convert route to DataFrame
    route_df = pd.DataFrame(
        route
    )

    # --------------------------------------------------------
    # Route order
    # --------------------------------------------------------

    route_df.insert(
        0,
        "route_order",
        range(
            1,
            len(route_df) + 1
        )
    )

    # --------------------------------------------------------
    # Calculate distances
    # --------------------------------------------------------

    distances = [0.0]

    for i in range(
        1,
        len(route_df)
    ):

        distance = (
            haversine_distance(

                route_df.iloc[
                    i - 1
                ]["latitude"],

                route_df.iloc[
                    i - 1
                ]["longitude"],

                route_df.iloc[
                    i
                ]["latitude"],

                route_df.iloc[
                    i
                ]["longitude"]

            )
        )

        distances.append(
            distance
        )

    route_df[
        "distance_from_previous_km"
    ] = distances

    # --------------------------------------------------------
    # Cumulative distance
    # --------------------------------------------------------

    route_df[
        "cumulative_distance_km"
    ] = (

        route_df[
            "distance_from_previous_km"
        ]

        .cumsum()

    )

    return route_df


